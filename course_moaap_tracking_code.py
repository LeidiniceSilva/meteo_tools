import matplotlib.gridspec as gridspec
import matplotlib.pyplot as plt
import cartopy.crs as ccrs
import cartopy.feature as cfeature

# Define colors
land = cfeature.NaturalEarthFeature(
    'physical', 'land', '110m',
    edgecolor='face',
    facecolor='#d2b48c'   # cor de terra
)

ocean = cfeature.NaturalEarthFeature(
    'physical', 'ocean', '110m',
    edgecolor='face',
    facecolor='#cceeff'   # azul claro
)

for tt in tqdm(range(len(time_datetime))):

    # Create a figure and axis with a PlateCarree projection (latitude and longitude)
    fig, ax = plt.subplots(subplot_kw={'projection': ccrs.PlateCarree()},
                          figsize=(14,6))

    # Set the extent of the map (in this case, the entire globe)
    # ax.set_extent([-180, 180, -90, 90], crs=ccrs.PlateCarree())

    # Map backgropund
    ax.add_feature(ocean, zorder=0)
    ax.add_feature(land, zorder=1)

    # Add coastlines and gridlines
    ax.coastlines(color='#969696', linewidth=0.8)
    ax.gridlines(linestyle='--', alpha=0.5)

    # MCSs
    sc = plt.contour(data_moaap['lon'],
                        data_moaap['lat'],
                        np.array(data_moaap['MCS_Tb_Objects'][tt,:,:]),
                        colors = '#33a02c')

    # Mid-Level Cyclones
    sc = plt.contour(data_moaap['lon'],
                        data_moaap['lat'],
                        np.array(data_moaap['CY_Objects'][tt,:,:])>0,
                        colors = 'k')

    # COL
    sc = plt.contour(data_moaap['lon'],
                        data_moaap['lat'],
                        np.array(data_moaap['CY_z500_Objects'][tt,:,:]),
                        colors = 'k', linestyles = '--')

    # Anticyclones
    sc = plt.contour(data_moaap['lon'],
                        data_moaap['lat'],
                        np.array(data_moaap['ACY_Objects'][tt,:,:]),
                        colors = '#ff7f00')

    # Jets
    sc = plt.contour(data_moaap['lon'],
                        data_moaap['lat'],
                        np.array(data_moaap['JET_Objects'][tt,:,:]),
                        colors = '#6a3d9a')

    # ARs
    sc = plt.contour(data_moaap['lon'],
                        data_moaap['lat'],
                        np.array(data_moaap['AR_Objects'][tt,:,:]),
                        colors = 'r')

    # Fronts
    sc = plt.contour(data_moaap['lon'],
                        data_moaap['lat'],
                        np.array(data_moaap['FR_Objects'][tt,:,:]),
                        colors = '#cab2d6',
                        linewidths = 0.5)

    # Equatorial Rossby Wave
    sc = plt.contour(data_moaap['lon'],
                        data_moaap['lat'],
                        np.array(data_moaap['ER_Objects'][tt,:,:]),
                        colors = '#8c510a',
                        linewidths = 0.5)

    ax.set_extent([-180, 180, -90, 90], crs=ccrs.PlateCarree())

    # Set the title of the plot
    plt.title('Objects identied by MOAAP at '+str(time_datetime[tt])[:16])

    # create legend
    for ob in range(len(object_names)):
      plt.plot([],[], color = object_names[ob][1], \
               linestyle = object_names[ob][2],\
               lw = object_names[ob][3],\
               label = object_names[ob][0])

    # plt.legend()
    ax.legend(bbox_to_anchor=(1, -0.05), ncol=4)

    # Show the plot
    fig.savefig('images/'+str(tt).zfill(3)+'_CausesOfExtreme.jpg', bbox_inches='tight', dpi=100)
    plt.close()

